const LocaleContext = createContext<{
  locale: UiLocale;
  setLocale: (locale: UiLocale) => void;
  t: (value: string) => string;
}>({ locale: 'fr', setLocale: () => undefined, t: (value) => value });

export function UiLocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<UiLocale>('fr');

  useEffect(() => {
    const saved = window.localStorage.getItem('mediflow-locale') as UiLocale | null;
    if (saved && saved in dictionaries) setLocaleState(saved);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
    window.localStorage.setItem('mediflow-locale', locale);
  }, [locale]);

  const value = useMemo(() => ({ locale, setLocale: setLocaleState, t: (text: string) => dictionaries[locale][text] ?? text }), [locale]);
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useUiLocale() { return useContext(LocaleContext); }
